
#!/usr/bin/env python3
"""
Generate UPSC GS-I module folders, module landing pages and chapter pages
from data/navigation.json.

Compatible with the GS-II navigation.js configuration structure:
{
    "site": {...},
    "interface": {...},
    "sections": [
        {
            "id": "...",
            "number": "01",
            "label": "...",
            "path": "module-folder/index.html",
            "description": "...",
            "explanation": "...",
            "studyGuidance": [],
            "examRelevance": "...",
            "chapters": [
                {
                    "id": "...",
                    "label": "...",
                    "path": "module-folder/chapter.html",
                    "status": "planned"
                }
            ]
        }
    ]
}

Safety:
- Creates missing files only.
- Never overwrites existing files.
- Does not modify navigation.json, CSS or JavaScript.
- Checks that configured paths remain inside the project folder.
"""

import argparse
import json
import os
from pathlib import Path, PurePosixPath
from html import escape


ROOT = Path(__file__).resolve().parent
CONFIG_FILE = ROOT / "data" / "navigation.json"


def load_config():
    if not CONFIG_FILE.exists():
        raise FileNotFoundError(
            f"Configuration file not found: {CONFIG_FILE}"
        )

    with CONFIG_FILE.open("r", encoding="utf-8") as file:
        config = json.load(file)

    if not isinstance(config.get("sections"), list):
        raise ValueError(
            'navigation.json must contain a "sections" array.'
        )

    return config


def safe_project_path(relative_path):
    """Resolve a configured path and reject paths outside the project."""

    if not isinstance(relative_path, str) or not relative_path.strip():
        raise ValueError("A configured page path is empty.")

    if "\\" in relative_path:
        raise ValueError(
            f"Use forward slashes in configured paths: {relative_path}"
        )

    pure_path = PurePosixPath(relative_path)

    if pure_path.is_absolute() or ".." in pure_path.parts:
        raise ValueError(
            f"Unsafe path outside project directory: {relative_path}"
        )

    target = (ROOT / Path(*pure_path.parts)).resolve()

    try:
        target.relative_to(ROOT.resolve())
    except ValueError:
        raise ValueError(
            f"Path escapes project directory: {relative_path}"
        )

    if target.suffix.lower() != ".html":
        raise ValueError(
            f"Expected an HTML file path: {relative_path}"
        )

    return target


def relative_asset_path(page_path, asset_path):
    """Calculate correct CSS/JS paths from each generated HTML page."""

    return Path(
        os.path.relpath(ROOT / asset_path, page_path.parent)
    ).as_posix()


def html_page_start(title, description, page_path):
    title = escape(title)
    description = escape(description or "UPSC GS-I study material.")

    css_path = escape(
        relative_asset_path(page_path, "css/style.css"),
        quote=True
    )

    js_path = escape(
        relative_asset_path(page_path, "js/navigation.js"),
        quote=True
    )

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">

  <meta name="description" content="{description}">
  <meta name="theme-color" content="#183b56">

  <title>{title} | UPSC GS-I</title>

  <link rel="stylesheet" href="{css_path}">
  <script src="{js_path}" defer></script>
</head>
"""


def module_template(section, page_path):
    label = escape(section.get("label", "Module"))
    description = escape(section.get("description", ""))
    explanation = escape(section.get("explanation", ""))

    return html_page_start(
        label,
        section.get("description", ""),
        page_path
    ) + f"""
<body>

  <!-- Shared header generated by navigation.js -->
  <header data-site-header></header>

  <main class="site-main" id="main-content">

    <!-- Dynamic breadcrumbs -->
    <nav
      class="breadcrumbs"
      data-breadcrumbs
      aria-label="Breadcrumb"
    ></nav>

    <!-- Module information from navigation.json -->
    <section
      class="module-introduction"
      data-module-content
      aria-labelledby="module-title"
    >
      <h1 id="module-title" data-page-title>{label}</h1>

      <p data-module-description>{description}</p>

      <p data-module-explanation>{explanation}</p>
    </section>

    <!-- Study guidance -->
    <section
      class="study-guidance"
      data-study-guidance
      aria-labelledby="study-guidance-title"
    >
      <h2 id="study-guidance-title">Study Guidance</h2>
      <ul data-study-guidance-list></ul>
    </section>

    <!-- Examination relevance -->
    <section
      class="module-metadata"
      data-exam-relevance
      aria-labelledby="exam-relevance-title"
    >
      <h2 id="exam-relevance-title">Examination Relevance</h2>
      <p data-exam-relevance-text></p>
    </section>

    <!-- Chapter directory -->
    <section
      class="chapter-directory"
      data-chapter-directory
      aria-labelledby="chapter-directory-title"
    >
      <h2 id="chapter-directory-title">Chapters in This Module</h2>

      <ol
        class="chapter-directory-list"
        data-chapter-list
      ></ol>
    </section>

  </main>

  <!-- Shared footer generated by navigation.js -->
  <footer data-site-footer></footer>

</body>
</html>
"""


def chapter_template(section, chapter, page_path):
    module_label = escape(section.get("label", "Module"))
    chapter_label = escape(chapter.get("label", "Chapter"))

    return html_page_start(
        chapter.get("label", "Chapter"),
        f"{chapter.get('label', 'Chapter')} — {section.get('label', 'UPSC GS-I')}",
        page_path
    ) + f"""
<body>

  <!-- Shared header -->
  <header data-site-header></header>

  <div class="page-layout">

    <!-- Dynamic chapter sidebar -->
    <aside
      class="secondary-navigation"
      data-secondary-navigation
      aria-label="Module chapter navigation"
    ></aside>

    <main class="main-content">

      <!-- Dynamic breadcrumbs -->
      <nav
        class="breadcrumbs"
        data-breadcrumbs
        aria-label="Breadcrumb"
      ></nav>

      <article class="chapter-content">

        <header class="chapter-header">
          <p class="chapter-module-label">{module_label}</p>
          <h1 data-page-title>{chapter_label}</h1>
        </header>

        <!--
          CHAPTER CONTENT GOES HERE.

          This is a structural placeholder only.
          Add researched, syllabus-aligned content later.
        -->

        <section class="chapter-placeholder">
          <h2>Chapter content</h2>
          <p>
            Content for this chapter has not yet been added.
          </p>
        </section>

      </article>

    </main>
  </div>

  <!-- Shared footer -->
  <footer data-site-footer></footer>

</body>
</html>
"""


def write_if_missing(path, content):
    """Create a file only if it does not already exist."""

    path.parent.mkdir(parents=True, exist_ok=True)

    if path.exists():
        print(f"SKIPPED (already exists): {path.relative_to(ROOT)}")
        return False

    path.write_text(content, encoding="utf-8")
    print(f"CREATED: {path.relative_to(ROOT)}")
    return True


def validate_section(section):
    required = ("id", "label", "path")

    for key in required:
        if not section.get(key):
            raise ValueError(
                f"Module is missing required field '{key}': {section}"
            )

    if not isinstance(section.get("chapters", []), list):
        raise ValueError(
            f"Chapters must be an array in module: {section['id']}"
        )


def generate():
    config = load_config()

    modules_created = 0
    chapters_created = 0
    modules_skipped = 0
    chapters_skipped = 0

    for section in config["sections"]:
        validate_section(section)

        module_path = safe_project_path(section["path"])

        module_html = module_template(section, module_path)

        if write_if_missing(module_path, module_html):
            modules_created += 1
        else:
            modules_skipped += 1

        for chapter in section.get("chapters", []):
            for key in ("id", "label", "path"):
                if not chapter.get(key):
                    raise ValueError(
                        f"Chapter in {section['id']} is missing '{key}': "
                        f"{chapter}"
                    )

            chapter_path = safe_project_path(chapter["path"])

            chapter_html = chapter_template(
                section,
                chapter,
                chapter_path
            )

            if write_if_missing(chapter_path, chapter_html):
                chapters_created += 1
            else:
                chapters_skipped += 1

    print("\n========== GENERATION SUMMARY ==========")
    print(f"Modules created:       {modules_created}")
    print(f"Chapters created:      {chapters_created}")
    print(f"Modules skipped:       {modules_skipped}")
    print(f"Chapters skipped:      {chapters_skipped}")
    print("Existing files were not overwritten.")
    print("========================================")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Generate GS-I module and chapter HTML files."
    )

    parser.parse_args()
    generate()
